print("\n1. Word2Vec 的核心思想")
print("""
传统方法：One-Hot 编码
  "猫" = [1, 0, 0, 0, ...]
  "狗" = [0, 1, 0, 0, ...]
  问题：无法表达语义关系，维度灾难

Word2Vec：分布式表示
  "猫" = [0.2, -0.1, 0.8, 0.3, ...]
  "狗" = [0.3, -0.2, 0.7, 0.4, ...]
  优势：低维稠密，语义相似度可计算
""")

print("\n2. 训练数据：从文本到训练对")
print("""
原始文本："我 爱 自然语言 处理"

Skip-Gram 窗口大小=2：
中心词="自然语言"，上下文=["我", "爱", "处理"]

生成训练对：
  ("自然语言", "我")
  ("自然语言", "爱")  
  ("自然语言", "处理")
  
目标：让模型学会"自然语言"经常和这些词一起出现
""")

print("\n3. 神经网络结构（简化版）")
print("""
输入层：One-Hot 向量（词表大小 V）
隐藏层：词向量矩阵 W（V×d 维）
输出层：Softmax 预测上下文词

前向传播：
  输入词 w → One-Hot(v) → h = W·v（得到词向量）
  → 输出层 → Softmax → 预测概率
  
反向传播：
  调整 W 矩阵，让预测更准确
  最终：W 的每一行就是一个词的向量！
""")

print("\n4. 负采样优化")
print("""
原始问题：Softmax 计算量太大（词表 V 可能几万）

解决方案：负采样（Negative Sampling）
  不再预测所有词的概率
  改为：区分正样本（真实上下文）和负样本（随机词）
  
例子：
  正样本：("自然语言", "处理") → 标签 1
  负样本：("自然语言", "桌子") → 标签 0
  负样本：("自然语言", "跑步") → 标签 0
  
训练更快，效果更好！
""")

print("\n5. 语义关系的数学解释")
print("""
为什么 Word2Vec 能学到语义关系？

假设词 A 和词 B 经常出现在相似上下文中：
  P(上下文|A) ≈ P(上下文|B)
  
那么训练后：
  向量(A) ≈ 向量(B)
  
因为神经网络要最小化：
  Loss = Σ |P(上下文|A) - P(上下文|B)|
  
最终：语义相似的词 → 向量相似
""")

print("\n6. 类比关系的奥秘")
print("""
为什么 国王 - 男人 + 女人 ≈ 女王？

设：国王 = K, 男人 = M, 女人 = W, 女王 = Q

观察上下文：
  国王的上下文：宫殿、王冠、统治...
  男人的上下文：父亲、儿子、工作...
  女人的上下文：母亲、女儿、工作...
  女王的上下文：宫殿、王冠、统治...

数学上：
  K - M + W 
  = (国王特征 - 男性特征 + 女性特征)
  ≈ 女王特征
  
因为：国王 ≈ 男性统治者
      女王 ≈ 女性统治者
""")

print("\n7. 实际向量计算演示")
print("让我们模拟 Word2Vec 学习到的向量：")

np.random.seed(42)

# 模拟词向量（假设已训练好）
vocab = {
    "猫": np.array([0.8, 0.2, -0.1, 0.5]),
    "狗": np.array([0.7, 0.3, -0.2, 0.6]),
    "老虎": np.array([0.9, 0.1, 0.1, 0.7]),
    "苹果": np.array([-0.2, 0.9, 0.3, -0.1]),
    "香蕉": np.array([-0.3, 0.8, 0.4, -0.2]),
    "国王": np.array([0.5, 0.3, 0.2, 0.7]),
    "男人": np.array([0.3, 0.2, 0.1, 0.5]),
    "女人": np.array([0.4, 0.3, 0.2, 0.6]),
    "女王": np.array([0.6, 0.4, 0.3, 0.8]),
}

def cosine_sim(a, b):
    return np.dot(a, b) / (np.linalg.norm(a) * np.linalg.norm(b))

print("\n语义相似度：")
print(f"  猫 vs 狗: {cosine_sim(vocab['猫'], vocab['狗']):.3f}")
print(f"  猫 vs 老虎: {cosine_sim(vocab['猫'], vocab['老虎']):.3f}")
print(f"  苹果 vs 香蕉: {cosine_sim(vocab['苹果'], vocab['香蕉']):.3f}")
print(f"  猫 vs 苹果: {cosine_sim(vocab['猫'], vocab['苹果']):.3f}")

print("\n类比关系验证：")
king = vocab["国王"]
man = vocab["男人"]
woman = vocab["女人"]
queen_calc = king - man + woman
queen_real = vocab["女王"]

print(f"  国王 - 男人 + 女人 计算结果: {queen_calc}")
print(f"  实际女王向量: {queen_real}")
print(f"  相似度: {cosine_sim(queen_calc, queen_real):.3f}")

print("\n8. Word2Vec 的局限性")
print("""
1. 一词一义：每个词只有一个向量，无法处理多义词
   "苹果"（水果）和"苹果"（公司）用同一个向量

2. 静态表示：训练后固定，无法根据上下文变化

3. 无法理解句子结构：只关注词语共现，忽略语法

4. 需要大量数据：小数据集效果差

后续改进：
  - ELMo：上下文相关词向量
  - BERT：双向Transformer，动态词向量
  - GPT：自回归语言模型
""")

print("\n9. Word2Vec vs 百科全书：本质区别")
print("""
百科全书：显性知识系统
  - 知识形式：文字描述、分类、关系
  - 创建方式：人工编写、编辑
  - 使用方式：阅读、理解、推理
  - 优点：准确、可解释、结构化
  - 缺点：成本高、更新慢、不完整

Word2Vec：隐性知识系统  
  - 知识形式：数值向量、统计规律
  - 创建方式：自动学习、数据驱动
  - 使用方式：数学计算、相似度查询
  - 优点：自动、快速、全面
  - 缺点：黑盒、不可解释、可能有偏见

关键区别：
  百科全书告诉你"猫是哺乳动物，有四条腿..."
  Word2Vec 告诉你"猫的向量接近狗，远离汽车"
  
  百科全书：你知道为什么
  Word2Vec：你不知道为什么，但能用
""")

